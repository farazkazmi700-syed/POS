const { createCipheriv, createDecipheriv, randomBytes } = require('node:crypto');
const { execFileSync, spawn } = require('node:child_process');
const { createReadStream, createWriteStream } = require('node:fs');
const fs = require('node:fs/promises');
const path = require('node:path');
const { Writable } = require('node:stream');
const { pipeline } = require('node:stream/promises');

const magic = Buffer.from('KZPOSBK1');
const headerSize = magic.length + 64 + 12;
const tagSize = 16;
const locations = { pgdata: '/var/lib/postgresql/data', uploads: '/data/invoices', queue: '/data/redis' };
const archivePaths = Object.values(locations).map(value => value.slice(1));
const pgdata = locations.pgdata + '/cluster';

function docker(args) {
  try {
    return execFileSync('docker', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 45_000 }).trim();
  } catch (error) {
    throw new Error('Docker operation ' + (error.code === 'ETIMEDOUT' ? 'timed out: ' : 'failed: ') + args.slice(0, 2).join(' '));
  }
}

function dockerStream(args, readArchive) {
  const child = spawn('docker', args, { stdio: readArchive ? ['ignore', 'pipe', 'ignore'] : ['pipe', 'ignore', 'ignore'] });
  const completion = new Promise(resolve => {
    child.on('error', () => resolve(false));
    child.on('close', code => resolve(code === 0));
  });
  return { child, completion };
}

async function keyFor(archivePath, keyPath) {
  const [archiveDir, actualKey] = await Promise.all([
    fs.realpath(path.dirname(archivePath)), fs.realpath(keyPath),
  ]);
  if (path.relative(archiveDir, path.dirname(actualKey)) === '') {
    throw new Error('Choose different directories for the backup and its key.');
  }
  const key = await fs.readFile(actualKey);
  if (key.length !== 32) throw new Error('Use a 32-byte backup key generated by keygen.');
  return key;
}

function assertShutdown(image, mountArgs) {
  const result = docker(['run', '--rm', '--network', 'none', ...mountArgs, '--env', 'LC_ALL=C',
    '--entrypoint', 'pg_controldata', image, pgdata]);
  const state = /^Database cluster state:[ \t]*(.+)$/m.exec(result)?.[1].trim();
  if (state !== 'shut down') {
    throw new Error('PostgreSQL must be cleanly shut down before a cold backup or restore (state: ' + (state ?? 'unknown') + ').');
  }
}

async function backup(container, archivePath, keyPath) {
  if (!/^[a-zA-Z0-9][a-zA-Z0-9_.-]*$/.test(container)) throw new Error('Invalid container name.');
  const key = await keyFor(archivePath, keyPath);
  const existing = await fs.lstat(archivePath).catch(error => { if (error.code !== 'ENOENT') throw error; });
  if (existing) throw new Error('A backup archive already exists at the destination.');
  const source = JSON.parse(docker(['inspect', '--type', 'container', '--format', '{{json .}}', container]));
  if (source.State.Status !== 'exited') throw new Error('Stop the POS container cleanly before taking a backup.');
  const image = source.Image;
  if (!/^sha256:[a-f0-9]{64}$/.test(image)) throw new Error('The source container has no immutable image ID.');

  const mounts = Object.values(locations).map(destination => {
    const mount = source.Mounts.find(item => item.Destination === destination && item.Type === 'volume');
    if (!mount || !/^[a-zA-Z0-9][a-zA-Z0-9_.-]*$/.test(mount.Name)) throw new Error('Required POS volume is missing.');
    if (docker(['ps', '-q', '--filter', 'volume=' + mount.Name])) throw new Error('A backup volume is still in use.');
    return 'type=volume,src=' + mount.Name + ',dst=' + destination + ',readonly';
  });
  if (new Set(mounts.map(value => value.split(',')[1])).size !== mounts.length) {
    throw new Error('The POS data paths must use separate named volumes.');
  }
  const mountArgs = mounts.flatMap(mount => ['--mount', mount]);
  assertShutdown(image, mountArgs);

  const staging = await fs.mkdtemp(path.join(path.dirname(archivePath), '.kazmion-backup-'));
  const temporary = path.join(staging, 'archive');
  try {
    const output = await fs.open(temporary, 'wx', 0o600);
    try {
      const nonce = randomBytes(12);
      const header = Buffer.concat([magic, Buffer.from(image.slice(7)), nonce]);
      const cipher = createCipheriv('aes-256-gcm', key, nonce);
      cipher.setAAD(header);
      await output.writeFile(header);
      const { child, completion } = dockerStream(['run', '--rm', '--network', 'none', ...mountArgs,
        '--entrypoint', 'tar', image, '-I', 'gzip -1', '-cf', '-', '-C', '/', ...archivePaths], true);
      const idle = setTimeout(() => {
        child.stdout.destroy(new Error('Docker archive stopped producing data.'));
        child.kill();
      }, 90_000);
      cipher.on('data', () => idle.refresh());
      try {
        await pipeline(child.stdout, cipher, createWriteStream(null, { fd: output.fd, autoClose: false }));
        if (!await completion) throw new Error('Docker could not archive the stopped POS volumes.');
        await output.writeFile(cipher.getAuthTag());
        await output.sync();
      } catch (error) {
        child.kill();
        await completion;
        throw error;
      } finally { clearTimeout(idle); }
    } finally { await output.close(); }
    // Publish a complete archive without replacing an existing backup.
    try { await fs.link(temporary, archivePath); }
    catch (error) {
      if (error.code === 'EEXIST') throw new Error('A backup archive already exists at the destination.');
      throw error;
    }
  } finally {
    await fs.unlink(temporary).catch(error => { if (error.code !== 'ENOENT') throw error; });
    await fs.rmdir(staging);
  }
  console.log('Encrypted backup complete.');
}

async function restore(archivePath, keyPath, prefix) {
  if (!/^pos-restore-[a-z0-9][a-z0-9-]{2,40}$/.test(prefix)) {
    throw new Error('Choose a new volume prefix starting with pos-restore-.');
  }
  const key = await keyFor(archivePath, keyPath);
  const input = await fs.open(archivePath, 'r');
  const created = [];
  try {
    const { size } = await input.stat();
    if (size <= headerSize + tagSize) throw new Error('Invalid or incomplete encrypted backup.');
    const header = Buffer.alloc(headerSize);
    const tag = Buffer.alloc(tagSize);
    await input.read(header, 0, header.length, 0);
    await input.read(tag, 0, tag.length, size - tagSize);
    const image = 'sha256:' + header.subarray(magic.length, magic.length + 64).toString();
    if (!header.subarray(0, magic.length).equals(magic) || !/^sha256:[a-f0-9]{64}$/.test(image)) {
      throw new Error('Invalid backup format.');
    }

    async function decrypt(destination) {
      const decipher = createDecipheriv('aes-256-gcm', key, header.subarray(-12));
      decipher.setAAD(header);
      decipher.setAuthTag(tag);
      const ciphertext = createReadStream(null, {
        fd: input.fd, autoClose: false, start: headerSize, end: size - tagSize - 1,
      });
      await pipeline(ciphertext, decipher, destination);
    }

    // Verify the entire ciphertext before handing any plaintext to tar.
    try { await decrypt(new Writable({ write(_chunk, _encoding, done) { done(); } })); }
    catch { throw new Error('Backup authentication failed. Check the key and archive integrity.'); }
    docker(['image', 'inspect', '--format', '{{.Id}}', image]);

    const existing = new Set(docker(['volume', 'ls', '-q']).split(/\r?\n/));
    const restoreId = randomBytes(8).toString('hex');
    const volumes = Object.fromEntries(Object.keys(locations).map(name => [name, prefix + '-' + name]));
    if (Object.values(volumes).some(name => existing.has(name))) throw new Error('A restore target volume already exists.');
    for (const volume of Object.values(volumes)) {
      docker(['volume', 'create', '--label', 'kazmion.restore=' + restoreId, volume]);
      const labels = JSON.parse(docker(['volume', 'inspect', '--format', '{{json .Labels}}', volume]));
      if (labels?.['kazmion.restore'] !== restoreId) throw new Error('A restore target was created by another process.');
      created.push(volume);
    }
    const mountArgs = Object.entries(volumes).flatMap(([name, volume]) => [
      '--mount', 'type=volume,src=' + volume + ',dst=' + locations[name] + ',volume-nocopy',
    ]);
    const { child, completion } = dockerStream(['run', '--rm', '-i', '--network', 'none', ...mountArgs,
      '--entrypoint', 'tar', image, '-xzpf', '-', '-C', '/'], false);
    try {
      await decrypt(child.stdin);
      if (!await completion) throw new Error('Could not extract the backup into the new volumes.');
    } catch (error) {
      child.kill();
      await completion;
      throw error;
    }
    assertShutdown(image, mountArgs);
    console.log(JSON.stringify({ image, volumes }));
  } catch (error) {
    for (const volume of created) {
      try { docker(['volume', 'rm', volume]); } catch { console.error('Could not clean up restore volume ' + volume); }
    }
    throw error;
  } finally {
    await input.close();
  }
}

async function main() {
  const [action, ...args] = process.argv.slice(2);
  if (action === 'keygen' && args.length === 1) {
    await fs.writeFile(args[0], randomBytes(32), { flag: 'wx', mode: 0o600 });
    console.log('Backup key created.');
  } else if (action === 'backup' && args.length === 3) {
    await backup(...args);
  } else if (action === 'restore' && args.length === 3) {
    await restore(...args);
  } else {
    throw new Error('Usage: keygen KEY | backup STOPPED_CONTAINER ARCHIVE KEY | restore ARCHIVE KEY pos-restore-PREFIX');
  }
}

main().catch(error => {
  console.error(error.code ? 'Backup operation failed (' + error.code + ').' : error.message);
  process.exitCode = 1;
});
